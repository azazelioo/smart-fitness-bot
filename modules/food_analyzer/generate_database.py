def generate_food_item(name, category, profile):
    """Generate a food item with realistic nutritional values"""
    base_cal, base_prot, base_fat, base_carb, var = profile
    
    # Add some variation to make data more realistic
    variation = 1 + random.uniform(-var, var)
    
    # Special adjustments for specific foods
    if "обезжиренн" in name or "0%" in name:
        base_fat = max(0.1, base_fat * 0.1)
        base_cal = base_cal * 0.6
    elif "жирн" in name or "сливочн" in name:
        base_fat = base_fat * 1.5
        base_cal = base_cal * 1.3
    
    if "жарен" in name or "фри" in name:
        base_fat = base_fat * 1.8
        base_cal = base_cal * 1.4
    
    if "отварн" in name or "на пару" in name:
        base_fat = base_fat * 0.5
        base_cal = base_cal * 0.8
    
    if "сладк" in name or "сахар" in name or "мёд" in name:
        base_carb = base_carb * 1.3
        base_cal = base_cal * 1.2
    
    # Generate realistic portion size based on category
    portion_sizes = {
        "fruits": random.choice([100, 120, 150, 180]),
        "vegetables": random.choice([100, 150, 200]),
        "meat": random.choice([100, 150, 200, 250]),
        "fish_seafood": random.choice([100, 150, 180]),
        "dairy": random.choice([100, 150, 200, 250]),
        "grains_cereals": random.choice([50, 80, 100, 150]),
        "legumes_nuts": random.choice([30, 50, 100]),
        "oils_fats": random.choice([10, 15, 20]),
        "sweets_desserts": random.choice([50, 80, 100, 150]),
        "beverages": random.choice([200, 250, 300, 350]),
        "soups": random.choice([250, 300, 350]),
        "salads": random.choice([150, 200, 250]),
        "main_dishes": random.choice([150, 200, 250, 300]),
        "fast_food": random.choice([150, 200, 250]),
        "asian_cuisine": random.choice([200, 250, 300, 350]),
        "sauces_condiments": random.choice([20, 30, 50]),
        "breakfast": random.choice([150, 200, 250]),
        "snacks": random.choice([30, 50, 100]),
        "baby_food": random.choice([80, 100, 120]),
        "diet_food": random.choice([100, 150, 200]),
        "sports_nutrition": random.choice([30, 50]),
        "ethnic_foods": random.choice([200, 250, 300, 350])
    }
    
    return {
        "name": name,
        "name_en": name.replace(" ", "_").lower(),
        "category": category,
        "calories": round(base_cal * variation, 1),
        "protein": round(base_prot * variation, 1),
        "fat": round(base_fat * variation, 1),
        "carbs": round(base_carb * variation, 1),
        "portion": portion_sizes.get(category, 100)
    }


def generate_variations(base_name, category, profile, cooking_methods=None, additions=None):
    """Generate variations of a food item"""
    items = []
    
    if cooking_methods is None:
        cooking_methods = [""]
    if additions is None:
        additions = [""]
    
    for method in cooking_methods:
        for addition in additions:
            name = base_name
            if method:
                name = f"{base_name} {method}"
            if addition:
                name = f"{name} {addition}"
            
            items.append(generate_food_item(name.strip(), category, profile))
    
    return items


